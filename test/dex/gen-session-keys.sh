#!/usr/bin/env bash
# LOCAL TEST ONLY. Writes dex/session-keys.env with a fresh random session key when it is missing.
# The file is git-ignored. Never copy its value anywhere outside the local test setup.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/session-keys.env"

if [ -f "$OUT" ]; then
  echo "exists: $OUT (left unchanged)"
  exit 0
fi

umask 077
{
  echo "# LOCAL TEST ONLY. Not for production. Generated by gen-session-keys.sh; git-ignored."
  echo "TEMPOLENS_SESSION_KEYS=$(openssl rand -base64 32)"
} > "$OUT"
chmod 600 "$OUT"
echo "wrote: $OUT"
